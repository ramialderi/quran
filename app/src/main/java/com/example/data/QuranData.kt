    fun getSurahForPage(page: Int): SurahInfo {
        // Return matching surah by page range
        return surahs.find { page in it.startPage..it.endPage } ?: surahs[0]
    }

    fun getJuzNumberForPage(page: Int): Int {
        val juzStarts = intArrayOf(
            1, 22, 42, 62, 82, 102, 121, 142, 162, 182,
            201, 222, 242, 262, 282, 302, 322, 342, 362, 382,
            402, 422, 442, 462, 482, 502, 522, 542, 562, 582
        )
        for (i in juzStarts.indices.reversed()) {
            if (page >= juzStarts[i]) {
                return i + 1
            }
        }
        return 1
    }

    fun getHizbNumberForPage(page: Int): Int {
        val calculated = ((page - 1) * 60 / 604) + 1
        return calculated.coerceIn(1, 60)
    }

