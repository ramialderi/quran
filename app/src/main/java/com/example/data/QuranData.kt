    fun searchSurahs(rawQuery: String): List<SurahInfo> {
        val q = rawQuery.trim()
        if (q.isBlank()) return surahs

        val qNorm = QuranSearchHelper.normalize(q)
        val qNoAl = qNorm.removePrefix("ال")
        val qDigits = QuranSearchHelper.toStandardDigits(q).filter { it.isDigit() }

        return surahs.filter { surah ->
            val nameNorm = QuranSearchHelper.normalize(surah.name)
            val nameNoAl = nameNorm.removePrefix("ال")
            val fullNorm = QuranSearchHelper.normalize(surah.fullName)

            if (qNorm.isNotEmpty() && (nameNorm.contains(qNorm) || nameNoAl.contains(qNoAl) || fullNorm.contains(qNorm))) {
                return@filter true
            }

            if (qDigits.isNotEmpty()) {
                if (surah.id.toString() == qDigits ||
                    surah.startPage.toString() == qDigits ||
                    surah.juzNumber.toString() == qDigits
                ) {
                    return@filter true
                }
            }

            if (qNorm.isNotEmpty() && surah.revelationType.contains(qNorm)) {
                return@filter true
            }

            false
        }
    }

    fun searchAyahs(rawQuery: String): List<SearchAyahResult> {
        val q = rawQuery.trim()
        if (q.isBlank()) return emptyList()

        val qNorm = QuranSearchHelper.normalize(q)
        val qDigits = QuranSearchHelper.toStandardDigits(q).filter { it.isDigit() }
        val results = mutableListOf<SearchAyahResult>()

        specialPages.forEach { (pageNumber, verses) ->
            val surah = getSurahForPage(pageNumber)
            verses.forEach { verse ->
                val vNorm = QuranSearchHelper.normalize(verse.text)
                val matchesKeyword = qNorm.length >= 2 && vNorm.contains(qNorm)
                val matchesAyahNumber = qDigits.isNotEmpty() && verse.ayahNumber.toString() == qDigits

                if (matchesKeyword || matchesAyahNumber) {
                    results.add(
                        SearchAyahResult(
                            surahId = surah.id,
                            surahName = surah.fullName,
                            ayahNumber = verse.ayahNumber,
                            pageNumber = pageNumber,
                            text = verse.text
                        )
                    )
                }
            }
        }

        return results
    }
