data class SearchAyahResult(
    val surahId: Int,
    val surahName: String,
    val ayahNumber: Int,
    val pageNumber: Int,
    val text: String
)

object QuranSearchHelper {
    private val tashkeelRegex = Regex("[\u064B-\u065F\u0670\u06D6-\u06ED]")
    private val alefRegex = Regex("[أإآٱ]")
    private val surahPrefixRegex = Regex("^(سورة|سوره|آية|ايه)\\s*")

    fun normalize(text: String): String {
        return text
            .replace(tashkeelRegex, "")
            .replace(alefRegex, "ا")
            .replace('ة', 'ه')
            .replace('ى', 'ي')
            .replace('ؤ', 'و')
            .replace('ئ', 'ي')
            .replace(surahPrefixRegex, "")
            .trim()
            .lowercase()
    }

    private val digitMap = mapOf(
        '٠' to '0', '١' to '1', '٢' to '2', '٣' to '3', '٤' to '4',
        '٥' to '5', '٦' to '6', '٧' to '7', '٨' to '8', '٩' to '9'
    )

    fun toStandardDigits(text: String): String {
        return text.map { digitMap[it] ?: it }.joinToString("")
    }
}
