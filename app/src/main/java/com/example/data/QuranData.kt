    fun getPage(pageNumber: Int): QuranPage {
        val validPage = pageNumber.coerceIn(1, 604)
        val surah = getSurahForPage(validPage)
        val juzNum = getJuzNumberForPage(validPage)
        val hizbNum = getHizbNumberForPage(validPage)

        val verses = specialPages[validPage] ?: generatePageVerses(validPage, surah)
        val isFirstPageOfSurah = validPage == surah.startPage
        val showBismillah = isFirstPageOfSurah && surah.id != 9 && surah.id != 1

        return QuranPage(
            pageNumber = validPage,
            surahName = surah.fullName,
            juzName = getJuzName(juzNum),
            juzNumber = juzNum,
            hizbNumber = hizbNum,
            verses = verses,
            showBismillah = showBismillah,
            surahBanner = if (isFirstPageOfSurah) surah.fullName else null
        )
    }

